"""Template-based emitter for the standard TileLang GEMM pattern.

Detects kernels matching:

    @tilelang.jit
    def matmul(A, B, block_M, block_N, block_K, dtype, accum_dtype):
        M, N, K = T.const(...)
        A: T.Tensor((M, K), dtype)
        B: T.Tensor((K, N), dtype)
        C = T.empty((M, N), dtype)
        with T.Kernel(ceildiv(N, block_N), ceildiv(M, block_M), threads=...) as (bx, by):
            A_shared = T.alloc_shared((block_M, block_K), dtype)
            B_shared = T.alloc_shared((block_K, block_N), dtype)
            C_local  = T.alloc_fragment((block_M, block_N), accum_dtype)
            T.clear(C_local)
            for k in T.Pipelined(ceildiv(K, block_K), num_stages=N):
                T.copy(A[by*block_M, k*block_K], A_shared)
                T.copy(B[k*block_K, bx*block_N], B_shared)
                T.gemm(A_shared, B_shared, C_local)
            T.copy(C_local, C[by*block_M, bx*block_N])
        return C

… and emits the validated LDS-staged FlyDSL form (tests/runnable/example_gemm.py).

Non-GEMM kernels fall back to the per-statement lowerer (still WIP for non-GEMM
shapes — see kernels with reductions/atomics/per-thread imperative code).

LIMITATIONS (v1):
- dtypes hardcoded fp16 in / fp32 acc; non-fp16 kernels fall through to fallback.
- 256-thread, 4-wave MFMA(16,16,16) tiling — the user's ``threads=`` value is
  recorded but the emitted launcher always uses 256 threads. Comment in output.
- B is assumed to be stored as ``(N, K)`` (FlyDSL convention), not TileLang's
  ``(K, N)``. The user must transpose B at the call site, or the result computes
  ``A @ B.T`` instead of ``A @ B``.
- Software pipelining (``num_stages > 1``) is recorded as a comment, not emitted.
"""

from __future__ import annotations

import ast
from typing import Optional

from ..kernel_ir import Alloc, Clear, Copy, Fill, Gemm, KernelIR, Pipelined, Serial


_TEMPLATE = '''\
# Generated by tilelang2flydsl from kernel '{kernel_name}'.
# NOTE: B is assumed to be stored as (N, K) — FlyDSL MFMA convention.
# If your TileLang source declares B as (K, N), transpose B at the call site,
# otherwise this kernel computes C = A @ B.T (not A @ B).
# NOTE: ``threads`` from T.Kernel is overridden to 256 (validated tiled_mma).
# NOTE: block_M/N/K are hardcoded as module constants — flyc.jit cannot accept
# them as Python ints (would become MLIR values, breaking make_tile).
import flydsl.compiler as flyc
import flydsl.expr as fx

{bm} = {bm_default}
{bn} = {bn_default}
{bk} = {bk_default}
{M} = {M_default}
{N} = {N_default}
{K} = {K_default}


@flyc.kernel
def {kernel_name}(
    {a_p}: fx.Tensor,
    {b_p}: fx.Tensor,
    {c_p}: fx.Tensor,
    tiled_mma: fx.TiledMma,
    tiled_copy_g2s_A: fx.TiledCopy,
    tiled_copy_g2s_B: fx.TiledCopy,
):
    tid = fx.thread_idx.x
    bid_x, bid_y, _ = fx.block_idx

    {a_p} = fx.rocdl.make_buffer_tensor({a_p}, max_size=False)
    {b_p} = fx.rocdl.make_buffer_tensor({b_p}, max_size=False)
    {c_p} = fx.rocdl.make_buffer_tensor({c_p}, max_size=False)

    gA_k = fx.flat_divide({a_p}, ({bm}, {bk}))[None, None, bid_y, None]
    gB_k = fx.flat_divide({b_p}, ({bn}, {bk}))[None, None, bid_x, None]
    gC = fx.flat_divide({c_p}, ({bm}, {bn}))[None, None, bid_y, bid_x]

    thr_mma = tiled_mma.thr_slice(tid)
    thr_copy_g2s_A = tiled_copy_g2s_A.get_slice(tid)
    thr_copy_g2s_B = tiled_copy_g2s_B.get_slice(tid)

    uni_copy_128b = fx.make_copy_atom(fx.UniversalCopy128b(), fx.Float16)
    buffer_copy_128b = fx.make_copy_atom(fx.rocdl.BufferCopy128b(), fx.Float16)
    buffer_copy_16b = fx.make_copy_atom(fx.rocdl.BufferCopy16b(), fx.Float16)

    thr_copy_s2r_A = fx.make_tiled_copy_A(buffer_copy_128b, tiled_mma).get_slice(tid)
    thr_copy_s2r_B = fx.make_tiled_copy_B(buffer_copy_128b, tiled_mma).get_slice(tid)
    thr_copy_r2g_C = fx.make_tiled_copy_C(buffer_copy_16b, tiled_mma).get_slice(tid)

    swizzle = fx.static(fx.SwizzleType.get(3, 3, 3))
    composed_A = fx.make_composed_layout(swizzle, fx.make_ordered_layout(({bm}, {bk}), (1, 0)))
    composed_B = fx.make_composed_layout(swizzle, fx.make_ordered_layout(({bn}, {bk}), (1, 0)))
    smem_base = fx.get_dyn_shared(fx.Float16)
    sA = fx.make_view(smem_base, composed_A)
    sB = fx.make_view(fx.add_offset(smem_base, {bm} * {bk}), composed_B)

    thr_gA_k = thr_copy_g2s_A.partition_S(gA_k)
    thr_sA = thr_copy_g2s_A.partition_D(sA)
    thr_gB_k = thr_copy_g2s_B.partition_S(gB_k)
    thr_sB = thr_copy_g2s_B.partition_D(sB)

    thr_sA_s2r = thr_copy_s2r_A.partition_S(sA)
    thr_sB_s2r = thr_copy_s2r_B.partition_S(sB)
    thr_gC = thr_copy_r2g_C.partition_S(gC)

    copy_frag_A = fx.make_fragment_like(thr_sA)
    copy_frag_B = fx.make_fragment_like(thr_sB)

    mma_frag_A = thr_mma.make_fragment_A(sA)
    mma_frag_B = thr_mma.make_fragment_B(sB)
    mma_frag_C = thr_mma.make_fragment_C(gC)

    mma_frag_A_retile = thr_copy_s2r_A.retile(mma_frag_A)
    mma_frag_B_retile = thr_copy_s2r_B.retile(mma_frag_B)

    mma_frag_C.fill(0)

    for k_iter in fx.range_constexpr({K} // {bk}):
        fx.copy(buffer_copy_128b, thr_gA_k[None, None, None, k_iter], copy_frag_A)
        fx.copy(buffer_copy_128b, thr_gB_k[None, None, None, k_iter], copy_frag_B)
        fx.copy(uni_copy_128b, copy_frag_A, thr_sA)
        fx.copy(uni_copy_128b, copy_frag_B, thr_sB)
        fx.gpu.barrier()
        for kk in fx.range_constexpr({bk} // 32):
            fx.copy(uni_copy_128b, thr_sA_s2r[None, None, kk], mma_frag_A_retile[None, None, kk])
            fx.copy(uni_copy_128b, thr_sB_s2r[None, None, kk], mma_frag_B_retile[None, None, kk])
            fx.gemm(
                tiled_mma,
                mma_frag_C,
                mma_frag_A[None, None, (None, kk)],
                mma_frag_B[None, None, (None, kk)],
                mma_frag_C,
                traversal_order=fx.GemmTraversalOrder.KNM,
            )
        fx.gpu.barrier()

    mma_frag_C_f16 = fx.make_fragment_like(mma_frag_C, fx.Float16.ir_type)
    mma_frag_C_retile = thr_copy_r2g_C.retile(mma_frag_C_f16)
    mma_frag_C_f16.store(fx.arith.trunc_f(fx.T.VectorType.get([64], fx.T.f16()), mma_frag_C.load()))
    fx.copy(buffer_copy_16b, mma_frag_C_retile, thr_gC)


@flyc.jit
def {kernel_name}_launch(
    {a_p}: fx.Tensor,
    {b_p}: fx.Tensor,
    {c_p}: fx.Tensor,
    stream: fx.Stream = fx.Stream(None),
):
    threads = 256
    val_per_thr = 8
    thrs_col = {bk} // val_per_thr
    thrs_row = threads // thrs_col

    tiled_copy_g2s_A = fx.make_tiled_copy(
        fx.make_copy_atom(fx.UniversalCopy128b(), fx.Float16),
        fx.make_layout(((thrs_col, thrs_row), (1, val_per_thr)),
                       ((thrs_row * val_per_thr, 1), (1, thrs_row))),
        fx.make_tile(thrs_row, {bk}),
    )
    tiled_copy_g2s_B = fx.make_tiled_copy(
        fx.make_copy_atom(fx.UniversalCopy128b(), fx.Float16),
        fx.make_layout(((thrs_col, thrs_row), (1, val_per_thr)),
                       ((thrs_row * val_per_thr, 1), (1, thrs_row))),
        fx.make_tile(thrs_row, {bk}),
    )
    tiled_mma = fx.make_tiled_mma(
        fx.make_mma_atom(fx.rocdl.MFMA(16, 16, 16, fx.Float16)),
        fx.make_layout((1, 4, 1), (0, 1, 0)),
        fx.make_tile(None, None, fx.make_layout((4, 4, 2), (1, 8, 4))),
    )

    smem_bytes = ({bm} + {bn}) * {bk} * 2
    {kernel_name}({a_p}, {b_p}, {c_p},
                  tiled_mma, tiled_copy_g2s_A, tiled_copy_g2s_B).launch(
        grid=({N} // {bn}, {M} // {bm}, 1),
        block=(threads, 1, 1),
        smem=smem_bytes,
        stream=stream,
    )
'''


def _iter_allocs(stmts):
    from ..kernel_ir import IfStmt, Parallel, Pipelined, Serial, Unroll, Vectorized

    for s in stmts:
        if isinstance(s, Alloc):
            yield s
        elif isinstance(s, (Pipelined, Parallel, Unroll, Vectorized, Serial)):
            yield from _iter_allocs(s.body)
        elif isinstance(s, IfStmt):
            yield from _iter_allocs(s.body)
            yield from _iter_allocs(s.orelse)


def _scalar_default_int(ir: KernelIR, name: str) -> Optional[int]:
    for p in ir.params:
        if p.name == name and p.kind == "scalar" and p.scalar and p.scalar.default is not None:
            d = p.scalar.default
            if isinstance(d, ast.Constant) and isinstance(d.value, int):
                return d.value
    return None


def _dtype_is_fp16(node: ast.expr) -> bool:
    """True if node is ``T.float16`` or a Name pointing to a scalar param whose
    default is T.float16."""
    if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
        if node.value.id == "T" and node.attr == "float16":
            return True
        if node.value.id == "fx" and node.attr == "Float16":
            return True
    return False


def match(ir: KernelIR) -> Optional[dict]:
    """Return a substitution dict if the IR matches the standard TileLang GEMM
    pattern, else None."""
    allocs = list(_iter_allocs(ir.body))
    shared = [a for a in allocs if a.kind == "shared"]
    frag = [a for a in allocs if a.kind == "fragment"]
    # >= 2 shared (allow an extra C_shared epilogue staging buffer) and exactly 1 fragment.
    if len(shared) < 2 or len(frag) != 1:
        return None

    # Find the single Pipelined/Serial K-loop containing 2 Copy + 1 Gemm.
    loops = [s for s in ir.body if isinstance(s, (Pipelined, Serial))]
    if len(loops) != 1:
        return None
    loop = loops[0]
    body_copies = [s for s in loop.body if isinstance(s, Copy)]
    body_gemms = [s for s in loop.body if isinstance(s, Gemm)]
    if len(body_copies) != 2 or len(body_gemms) != 1:
        return None

    # At least one trailing Copy whose source is the fragment (epilogue store).
    # The kernel may emit additional Copy(fragment, C_shared) + Copy(C_shared, C)
    # stages — we ignore those intermediate LDS hops; the runnable template
    # writes the fragment directly to gmem.
    c_frag = frag[0]
    epilogue_copies = [
        s for s in ir.body
        if isinstance(s, Copy)
        and isinstance(s.src_expr, ast.Name)
        and s.src_expr.id == c_frag.name
    ]
    if not epilogue_copies:
        return None

    # Optional Clear targeting the fragment.
    has_clear_or_fill = any(
        isinstance(s, (Clear, Fill)) for s in ir.body
    )
    if not has_clear_or_fill:
        return None

    a_shared = next((a for a in shared if a.name == "A_shared"), shared[0])
    b_shared = next((a for a in shared if a.name == "B_shared"), shared[1])

    if len(a_shared.shape) != 2 or len(b_shared.shape) != 2 or len(c_frag.shape) != 2:
        return None
    if not all(isinstance(x, ast.Name) for x in [*a_shared.shape, *b_shared.shape, *c_frag.shape]):
        return None
    bm_a, bk_a = a_shared.shape[0].id, a_shared.shape[1].id
    bm_c, bn_c = c_frag.shape[0].id, c_frag.shape[1].id
    if bm_a != bm_c:
        return None
    # B_shared may be (block_K, block_N) (TileLang convention) OR
    # (block_N, block_K) (FlyDSL convention). Accept either.
    if b_shared.shape[0].id == bk_a and b_shared.shape[1].id == bn_c:
        pass  # (BK, BN)
    elif b_shared.shape[0].id == bn_c and b_shared.shape[1].id == bk_a:
        pass  # (BN, BK)
    else:
        return None
    bn_b = bn_c

    # Dtypes must resolve to fp16/fp32 (only validated path so far).
    a_dtype = a_shared.dtype
    if isinstance(a_dtype, ast.Name):
        # Resolve param default
        for p in ir.params:
            if p.name == a_dtype.id and p.scalar and p.scalar.default is not None:
                if not _dtype_is_fp16(p.scalar.default):
                    return None
                break
    elif not _dtype_is_fp16(a_dtype):
        return None

    tensor_params = [p for p in ir.params if p.kind == "tensor"]
    if len(tensor_params) < 2:
        return None
    a_param = tensor_params[0]
    b_param = tensor_params[1]
    a_p = a_param.name
    b_p = b_param.name

    # Resolve M, N, K. Prefer TileLang ``T.const("M, N, K")`` symbols; otherwise
    # extract them from the A/B/C tensor shape annotations.
    if len(ir.const_names) == 3:
        M, N, K = ir.const_names
    else:
        # A: (M, K), B: (N, K) or (K, N) — pick whichever isn't shared with A.
        if not a_param.tensor or len(a_param.tensor.shape) != 2:
            return None
        a_shape = a_param.tensor.shape
        if not (isinstance(a_shape[0], ast.Name) and isinstance(a_shape[1], ast.Name)):
            return None
        M, K = a_shape[0].id, a_shape[1].id
        # N from C: shape (M, N)
        c_param = next((p for p in tensor_params if p.name not in (a_p, b_p)), None)
        if c_param is None or len(tensor_params) >= 3:
            c_param = tensor_params[2] if len(tensor_params) >= 3 else None
        if c_param and c_param.tensor and len(c_param.tensor.shape) == 2:
            cn = c_param.tensor.shape[1]
            N = cn.id if isinstance(cn, ast.Name) else "N"
        else:
            N = "N"

    c_p = ir.returns or (tensor_params[2].name if len(tensor_params) >= 3 else "C")

    return {
        "kernel_name": ir.name,
        "a_p": a_p,
        "b_p": b_p,
        "c_p": c_p,
        "M": M,
        "N": N,
        "K": K,
        "bm": bm_a,
        "bn": bn_b,
        "bk": bk_a,
        "bm_default": _scalar_default_int(ir, bm_a) or 128,
        "bn_default": _scalar_default_int(ir, bn_b) or 128,
        "bk_default": _scalar_default_int(ir, bk_a) or 64,
        # M/N/K are TileLang ``T.const(...)`` symbols — no source defaults; use 1024.
        # Edit the emitted file to retarget a different size.
        "M_default": 1024,
        "N_default": 1024,
        "K_default": 1024,
    }


def emit(info: dict) -> ast.Module:
    return ast.parse(_TEMPLATE.format(**info))
