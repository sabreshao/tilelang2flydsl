"""Template-based emitter for tile_kernels/moe/topk_gate_kernel.py.

Detects the per-token iterative-argmax pattern:

    @tilelang.jit(...)
    def get_topk_gate_kernel(num_experts: int, num_topk: int):
        num_threads = 32
        num_tokens = T.dynamic(...)
        num_aligned_experts = align(num_experts, num_threads)

        @T.prim_func
        def topk_gate_kernel(
            scores: T.Tensor[(num_tokens, num_experts), T.float32],
            topk_idx: T.Tensor[(num_tokens, num_topk), T.int64],
        ):
            with T.Kernel(num_tokens, threads=num_threads) as pid:
                scores_fragment = T.alloc_fragment((num_aligned_experts,), T.float32)
                amax_fragment = T.alloc_fragment((1,), T.float32)
                idx_fragment = T.alloc_fragment((num_aligned_experts,), T.int32)
                idx_reducer = T.alloc_reducer((1,), T.int32, 'min', replication='all')
                topk_idx_shared = T.alloc_shared((num_topk,), T.int32)
                ...
                for k in T.unroll(num_topk):
                    T.reduce_max(...)        # cross-thread max
                    T.fill(idx_reducer, ...)
                    for i in T.Parallel(...): ...
                    T.finalize_reducer(idx_reducer)  # cross-thread min
                    ...

… and emits the validated FlyDSL form (see tests/runnable/topk_gate.py):
per-thread register accumulators, wave-shuffle reduction across the active
32 lanes (shuffle_xor with mask=32 on the CDNA3 64-wide wave),
iterative argmax with stable-index tie-breaking.

LIMITATIONS (v1):
- fp32 scores → int64 topk_idx (the only configuration used in practice).
- NUM_EXPERTS / NUM_TOPK / NUM_TOKENS hardcoded as module constants. Edit
  the emitted file to retune.
- Always uses 32 threads (matches the TileLang kernel's ``num_threads = 32``
  and stays within one half-wave on CDNA3). Larger workloads should split
  across more blocks.
"""

from __future__ import annotations

import ast
from typing import Optional

from ..kernel_ir import (
    Alloc,
    Gemm,
    IfStmt,
    KernelIR,
    Parallel,
    Pipelined,
    Raw,
    Serial,
    Unroll,
    Vectorized,
)


_TEMPLATE = '''\
# Generated by tilelang2flydsl from kernel '{kernel_name}'.
# Per-token iterative argmax. Lowers TileLang's T.reduce_max / T.alloc_reducer
# /T.finalize_reducer to FlyDSL shuffle_xor-based wave reduction across the
# active {num_threads} lanes. Edit module constants below to retune.
import math
import flydsl.compiler as flyc
import flydsl.expr as fx
from flydsl.expr.typing import T


def _align(x, m):
    return ((x + m - 1) // m) * m


NUM_EXPERTS = {num_experts_default}
NUM_TOPK = {num_topk_default}
NUM_THREADS = {num_threads}
WAVE_MASK = {num_threads}
NUM_ALIGNED_EXPERTS = _align(NUM_EXPERTS, NUM_THREADS)
ELEMS_PER_THREAD = NUM_ALIGNED_EXPERTS // NUM_THREADS

NUM_TOKENS = {num_tokens_default}
NEG_INF = float('-inf')
INT32_MAX_VAL = 2**31 - 1


@flyc.kernel
def {kernel_name}({scores_p}: fx.Tensor, {topk_p}: fx.Tensor):
    {pid} = fx.block_idx.x
    tid = fx.thread_idx.x

    {scores_p}_g = fx.rocdl.make_buffer_tensor({scores_p}, max_size=False)
    {topk_p}_g = fx.rocdl.make_buffer_tensor({topk_p}, max_size=False)

    neg_inf = fx.Float32(NEG_INF)
    int_max = fx.Int32(INT32_MAX_VAL)

    # Per-thread register arrays (Python lists — fully unrolled at trace time).
    scores_reg = [neg_inf for _ in range(ELEMS_PER_THREAD)]
    idx_reg = [fx.Int32(0) for _ in range(ELEMS_PER_THREAD)]

    # Load scores; mask out invalid lanes with -inf.
    for j in fx.range_constexpr(ELEMS_PER_THREAD):
        i = tid + j * NUM_THREADS
        in_range = i < NUM_EXPERTS
        safe_i = in_range.select(i, fx.Int32(0))
        v = {scores_p}_g[{pid}, safe_i]
        scores_reg[j] = in_range.select(v, neg_inf)
        idx_reg[j] = i

    for k in fx.range_constexpr(NUM_TOPK):
        # 1. Per-thread max of register slice.
        local_max = scores_reg[0]
        for j in fx.range_constexpr(1, ELEMS_PER_THREAD):
            local_max = local_max.maximumf(scores_reg[j])
        # 2. Wave-reduce max across NUM_THREADS lanes.
        w = local_max
        for sh in fx.range_constexpr(int(math.log2(WAVE_MASK))):
            off = WAVE_MASK // (2 << sh)
            peer = w.shuffle_xor(off, WAVE_MASK)
            w = w.maximumf(peer)
        amax = w
        # 3. Per-thread min of indices matching amax.
        local_min = int_max
        for j in fx.range_constexpr(ELEMS_PER_THREAD):
            match = (scores_reg[j] == amax).select(idx_reg[j], int_max)
            local_min = (local_min <= match).select(local_min, match)
        # 4. Wave-reduce min across NUM_THREADS lanes.
        m = local_min
        for sh in fx.range_constexpr(int(math.log2(WAVE_MASK))):
            off = WAVE_MASK // (2 << sh)
            peer = m.shuffle_xor(off, WAVE_MASK)
            m = (m <= peer).select(m, peer)
        min_idx = m
        # 5. Single-thread write of the chosen index (extsi to int64).
        if tid == 0:
            {topk_p}_g[{pid}, k] = min_idx.extsi(T.i64)
        # 6. Mask the chosen position out for the next iteration.
        for j in fx.range_constexpr(ELEMS_PER_THREAD):
            scores_reg[j] = (idx_reg[j] == min_idx).select(neg_inf, scores_reg[j])


@flyc.jit
def {kernel_name}_launch({scores_p}: fx.Tensor, {topk_p}: fx.Tensor,
                          stream: fx.Stream = fx.Stream(None)):
    {kernel_name}({scores_p}, {topk_p}).launch(
        grid=(NUM_TOKENS, 1, 1), block=(NUM_THREADS, 1, 1), stream=stream,
    )
'''


def _iter_stmts(stmts):
    for s in stmts:
        yield s
        if isinstance(s, (Pipelined, Parallel, Unroll, Vectorized, Serial)):
            yield from _iter_stmts(s.body)
        elif isinstance(s, IfStmt):
            yield from _iter_stmts(s.body)
            yield from _iter_stmts(s.orelse)


def _closure_int(ir: KernelIR, name: str, default: int) -> int:
    v = ir.closure.values.get(name)
    return v if isinstance(v, int) else default


def match(ir: KernelIR) -> Optional[dict]:
    """Detect the topk_gate iterative-argmax pattern."""
    # 2 tensor params: scores (2D), topk_idx (2D).
    tensor_params = [p for p in ir.params if p.kind == "tensor"]
    if len(tensor_params) != 2:
        return None
    scores_p, topk_p = tensor_params
    if not (scores_p.tensor and topk_p.tensor):
        return None
    if len(scores_p.tensor.shape) != 2 or len(topk_p.tensor.shape) != 2:
        return None

    # 1D grid.
    if len(ir.grid) != 1 or len(ir.block_axes) != 1:
        return None

    # No GEMM.
    if any(isinstance(s, Gemm) for s in _iter_stmts(ir.body)):
        return None

    # Body must contain at least one reduction call (Raw stmt whose note
    # mentions reduce_max / reduce_min / etc.) — distinguishes from
    # reduce_fused (no T.reduce_* calls).
    saw_reduction = any(
        isinstance(s, Raw)
        and isinstance(s.note, str)
        and ("reduce_max" in s.note or "reduce_min" in s.note or "finalize_reducer" in s.note)
        for s in _iter_stmts(ir.body)
    )
    if not saw_reduction:
        return None

    # Must have a Pipelined/Unroll/Serial loop wrapping the body (the
    # k-iteration over num_topk).
    has_outer_loop = any(
        isinstance(s, (Pipelined, Unroll, Serial)) for s in ir.body
    )
    if not has_outer_loop:
        return None

    pid = ir.block_axes[0]
    num_threads = _closure_int(ir, "num_threads", 32)

    return {
        "kernel_name": ir.name,
        "scores_p": scores_p.name,
        "topk_p": topk_p.name,
        "pid": pid,
        "num_threads": num_threads,
        # Factory args — no source defaults; pick reasonable values. Edit
        # the emitted module-level constants to retune.
        "num_experts_default": 32,
        "num_topk_default": 4,
        "num_tokens_default": 16,
    }


def emit(info: dict) -> ast.Module:
    return ast.parse(_TEMPLATE.format(**info))
