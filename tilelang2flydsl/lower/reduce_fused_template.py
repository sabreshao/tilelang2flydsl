"""Template-based emitter for tile_kernels/moe/reduce_fused_kernel.py.

Detects kernels matching:

    @tilelang.jit(...)
    def get_reduce_fused_kernel(hidden, num_topk, in_dtype, out_dtype,
                                 with_sf, with_weights, with_x_sf):
        num_threads = 128
        num_tokens = T.dynamic(...)
        num_expanded_tokens = T.dynamic(...)

        @T.prim_func
        def reduce_fused_kernel(
            x: T.Tensor[(num_expanded_tokens, hidden), in_dtype],
            topk_weights: T.Tensor[(num_tokens, num_topk), T.float32],
            token_topk_to_pos: T.Tensor[(num_tokens, num_topk), T.int32],
            out: T.Tensor[(num_tokens, hidden), out_dtype],
            sf: T.Tensor[(1,), T.float32],
            x_sf: T.Tensor[(num_expanded_tokens,), T.float32],
        ):
            ...

… and emits a per-token weighted gather-and-accumulate kernel — fp32 input,
fp32 output, all three flags (with_sf, with_weights, with_x_sf) set to True
(the most-featured path).

LIMITATIONS (v1):
- HIDDEN / NUM_TOPK / NUM_TOKENS / NUM_EXPANDED_TOKENS hardcoded as module
  constants — edit emitted file to retune.
- Always emits the WITH_SF=WITH_WEIGHTS=WITH_X_SF=True path. Other flag
  combinations require manual editing (drop the unused multiplications).
- fp32 in / fp32 out only.
- TileLang ``if pos >= 0`` runtime guard is lowered as predication
  (``mask = (pos>=0).select(1.0, 0.0)``) — equivalent, avoids flydsl's
  single-exit constraints on accumulator writes inside scf.if.
"""

from __future__ import annotations

import ast
from typing import Optional

from ..kernel_ir import Gemm, KernelIR, Parallel


_TEMPLATE = '''\
# Generated by tilelang2flydsl from kernel '{kernel_name}'.
# Per-token weighted gather-and-accumulate. Emits the WITH_SF=WITH_WEIGHTS=
# WITH_X_SF=True path; edit the body to drop unused multiplications for
# other flag combinations. fp32 only. Edit module constants below to retune.
import flydsl.compiler as flyc
import flydsl.expr as fx

HIDDEN = {hidden_default}
NUM_TOPK = {num_topk_default}
NUM_THREADS = {num_threads}
ELEMS_PER_THREAD = HIDDEN // NUM_THREADS

NUM_TOKENS = {num_tokens_default}
NUM_EXPANDED_TOKENS = {num_expanded_default}


@flyc.kernel
def {kernel_name}(
    {x_p}: fx.Tensor,
    {tw_p}: fx.Tensor,
    {pos_p}: fx.Tensor,
    {out_p}: fx.Tensor,
    {sf_p}: fx.Tensor,
    {xsf_p}: fx.Tensor,
):
    {pid} = fx.block_idx.x
    tid = fx.thread_idx.x

    {x_p}_g = fx.rocdl.make_buffer_tensor({x_p}, max_size=False)
    {tw_p}_g = fx.rocdl.make_buffer_tensor({tw_p}, max_size=False)
    {pos_p}_g = fx.rocdl.make_buffer_tensor({pos_p}, max_size=False)
    {out_p}_g = fx.rocdl.make_buffer_tensor({out_p}, max_size=False)
    {sf_p}_g = fx.rocdl.make_buffer_tensor({sf_p}, max_size=False)
    {xsf_p}_g = fx.rocdl.make_buffer_tensor({xsf_p}, max_size=False)

    # Per-thread register accumulators (Python list — fully unrolled by tracing).
    acc = [fx.Float32(0.0) for _ in range(ELEMS_PER_THREAD)]

    sf_val = {sf_p}_g[0]

    for k in fx.range_constexpr(NUM_TOPK):
        pos = {pos_p}_g[{pid}, k]
        # Predicate: 1.0 when pos >= 0, else 0.0. Index with clamped pos to avoid OOB.
        valid_f = (pos >= 0).select(fx.Float32(1.0), fx.Float32(0.0))
        safe_pos = (pos >= 0).select(pos, fx.Int32(0))

        w = {tw_p}_g[{pid}, k] * {xsf_p}_g[safe_pos] * valid_f

        for j in fx.range_constexpr(ELEMS_PER_THREAD):
            col = tid + j * NUM_THREADS
            acc[j] = acc[j] + {x_p}_g[safe_pos, col] * w

    for j in fx.range_constexpr(ELEMS_PER_THREAD):
        col = tid + j * NUM_THREADS
        {out_p}_g[{pid}, col] = acc[j] * sf_val


@flyc.jit
def {kernel_name}_launch(
    {x_p}: fx.Tensor,
    {tw_p}: fx.Tensor,
    {pos_p}: fx.Tensor,
    {out_p}: fx.Tensor,
    {sf_p}: fx.Tensor,
    {xsf_p}: fx.Tensor,
    stream: fx.Stream = fx.Stream(None),
):
    {kernel_name}({x_p}, {tw_p}, {pos_p}, {out_p}, {sf_p}, {xsf_p}).launch(
        grid=(NUM_TOKENS, 1, 1), block=(NUM_THREADS, 1, 1), stream=stream,
    )
'''


def _iter_stmts(stmts):
    from ..kernel_ir import IfStmt, Pipelined, Serial, Unroll, Vectorized

    for s in stmts:
        yield s
        if isinstance(s, (Pipelined, Parallel, Unroll, Vectorized, Serial)):
            yield from _iter_stmts(s.body)
        elif isinstance(s, IfStmt):
            yield from _iter_stmts(s.body)
            yield from _iter_stmts(s.orelse)


def _closure_int(ir: KernelIR, name: str, default: int) -> int:
    v = ir.closure.values.get(name)
    return v if isinstance(v, int) else default


def match(ir: KernelIR) -> Optional[dict]:
    """Detect the reduce_fused pattern. Returns substitution dict or None."""
    # 6 tensor params with the expected shapes.
    tensor_params = [p for p in ir.params if p.kind == "tensor"]
    if len(tensor_params) != 6:
        return None

    # Expected shape signature (last-dim names matched, not literal names):
    #   x:                 (num_expanded_tokens, hidden)        2D
    #   topk_weights:      (num_tokens, num_topk)               2D
    #   token_topk_to_pos: (num_tokens, num_topk)               2D
    #   out:               (num_tokens, hidden)                 2D
    #   sf:                (1,)                                  1D
    #   x_sf:              (num_expanded_tokens,)               1D
    shapes = [len(p.tensor.shape) if p.tensor else 0 for p in tensor_params]
    if shapes != [2, 2, 2, 2, 1, 1]:
        return None

    # 1D grid, single axis.
    if len(ir.grid) != 1 or len(ir.block_axes) != 1:
        return None

    # No GEMM in body — this isn't a tile-MMA kernel.
    if any(isinstance(s, Gemm) for s in _iter_stmts(ir.body)):
        return None

    # Pull dimension symbols from the tensor shapes.
    x, tw, pos, out, sf, xsf = tensor_params
    if not (x.tensor and out.tensor and tw.tensor and xsf.tensor):
        return None
    if not all(isinstance(e, ast.Name) for e in [*x.tensor.shape, *out.tensor.shape, *tw.tensor.shape]):
        return None
    # x[:, hidden] should match out[:, hidden]
    if x.tensor.shape[1].id != out.tensor.shape[1].id:
        return None

    pid = ir.block_axes[0]
    num_threads = _closure_int(ir, "num_threads", 128)

    return {
        "kernel_name": ir.name,
        "x_p": x.name,
        "tw_p": tw.name,
        "pos_p": pos.name,
        "out_p": out.name,
        "sf_p": sf.name,
        "xsf_p": xsf.name,
        "pid": pid,
        "num_threads": num_threads,
        # No source defaults for hidden / num_topk / runtime shapes; pick reasonable
        # values. Edit the emitted module-level constants to retune.
        "hidden_default": 256,
        "num_topk_default": 4,
        "num_tokens_default": 16,
        "num_expanded_default": 64,
    }


def emit(info: dict) -> ast.Module:
    return ast.parse(_TEMPLATE.format(**info))
