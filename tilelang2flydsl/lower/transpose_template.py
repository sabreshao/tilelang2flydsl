"""Template-based emitter for the batched-transpose TileLang kernel.

Detects kernels matching:

    @tilelang.jit(...)
    def get_batched_transpose_kernel(...):
        num_batches = T.dynamic(...)
        shape_x = T.dynamic(...)
        shape_y = T.dynamic(...)
        ...

        @T.prim_func
        def batched_transpose_kernel(
            x: T.StridedTensor[(num_batches, shape_x, shape_y), ...],
            out: T.Tensor[(num_batches, shape_y, shape_x), dtype],
        ):
            with T.Kernel(shape_y // block_y, shape_x // block_x, num_batches,
                          threads=num_threads) as (pid_y, pid_x, pid_batch):
                # ... LDS-staged + swizzled transpose body ...

… and emits a simplified direct gmem→gmem element-wise transpose. The
LDS-staging + bank-conflict swizzle optimization in the original TileLang
kernel is dropped — output is correct but slower than the optimized form.

LIMITATIONS (v1):
- BLOCK_X / BLOCK_Y / NUM_THREADS hardcoded as module constants. Edit the
  emitted file to retune.
- num_batches / shape_x / shape_y also hardcoded as module constants (default
  values picked for a typical workload). Edit to change.
- Drops T.Parallel custom loop_layout, T.assume, T.alloc_local, T.alloc_shared,
  T.sync_threads — all subsumed by the simpler element-wise form.
"""

from __future__ import annotations

import ast
from typing import Optional

from ..kernel_ir import (
    Alloc,
    Assign,
    Assume,
    Copy,
    DynamicSym,
    Gemm,
    KernelIR,
    Parallel,
    Pipelined,
    SyncThreads,
    Unroll,
)


_TEMPLATE = '''\
# Generated by tilelang2flydsl from kernel '{kernel_name}'.
# Simplified direct gmem→gmem transpose. The TileLang fixture's LDS-staging +
# XOR swizzle for coalesced writes is dropped — output is correct but slower.
# Edit module constants below to retune block / shape sizes.
import flydsl.compiler as flyc
import flydsl.expr as fx

BLOCK_X = {block_x_default}
BLOCK_Y = {block_y_default}
NUM_THREADS = {num_threads_default}
ELEMS_PER_THREAD = (BLOCK_X * BLOCK_Y) // NUM_THREADS

NUM_BATCHES = {num_batches_default}
SHAPE_X = {shape_x_default}
SHAPE_Y = {shape_y_default}


@flyc.kernel
def {kernel_name}({x_p}: fx.Tensor, {out_p}: fx.Tensor):
    {pid_y} = fx.block_idx.x
    {pid_x} = fx.block_idx.y
    {pid_b} = fx.block_idx.z
    tid = fx.thread_idx.x

    {x_p}_g = fx.rocdl.make_buffer_tensor({x_p}, max_size=False)
    {out_p}_g = fx.rocdl.make_buffer_tensor({out_p}, max_size=False)

    for k_iter in fx.range_constexpr(ELEMS_PER_THREAD):
        idx = tid + k_iter * NUM_THREADS
        i = idx // BLOCK_X
        j = idx % BLOCK_X
        v = {x_p}_g[{pid_b}, {pid_x} * BLOCK_X + j, {pid_y} * BLOCK_Y + i]
        {out_p}_g[{pid_b}, {pid_y} * BLOCK_Y + i, {pid_x} * BLOCK_X + j] = v


@flyc.jit
def {kernel_name}_launch({x_p}: fx.Tensor, {out_p}: fx.Tensor,
                          stream: fx.Stream = fx.Stream(None)):
    {kernel_name}({x_p}, {out_p}).launch(
        grid=(SHAPE_Y // BLOCK_Y, SHAPE_X // BLOCK_X, NUM_BATCHES),
        block=(NUM_THREADS, 1, 1),
        stream=stream,
    )
'''


def _iter_stmts(stmts):
    """Recursive yield of every Stmt in the IR body."""
    from ..kernel_ir import IfStmt, Serial, Vectorized

    for s in stmts:
        yield s
        if isinstance(s, (Pipelined, Parallel, Unroll, Vectorized, Serial)):
            yield from _iter_stmts(s.body)
        elif isinstance(s, IfStmt):
            yield from _iter_stmts(s.body)
            yield from _iter_stmts(s.orelse)


def _closure_int(ir: KernelIR, name: str, default: int) -> int:
    v = ir.closure.values.get(name)
    return v if isinstance(v, int) else default


def match(ir: KernelIR) -> Optional[dict]:
    """Detect the batched-transpose pattern. Returns substitution dict or None."""
    # 2 tensor params; both 3D.
    tensor_params = [p for p in ir.params if p.kind == "tensor"]
    if len(tensor_params) != 2:
        return None
    x_param, out_param = tensor_params
    if not x_param.tensor or not out_param.tensor:
        return None
    if len(x_param.tensor.shape) != 3 or len(out_param.tensor.shape) != 3:
        return None

    # 3D grid (shape_y // block_y, shape_x // block_x, num_batches).
    if len(ir.grid) != 3:
        return None
    if len(ir.block_axes) != 3:
        return None

    # No GEMM, no MMA fragment — distinguishes from the GEMM pattern.
    stmts = list(_iter_stmts(ir.body))
    if any(isinstance(s, Gemm) for s in stmts):
        return None
    allocs = [s for s in stmts if isinstance(s, Alloc) and s.kind == "fragment"]
    if allocs:
        return None

    # Expect at least one Parallel or per-thread Assign — signals an imperative
    # body, not a tile-MMA body.
    has_parallel = any(isinstance(s, Parallel) for s in stmts)
    has_per_thread_assign = any(
        isinstance(s, Assign) and isinstance(s.target, ast.Subscript) for s in stmts
    )
    if not (has_parallel or has_per_thread_assign):
        return None

    # Verify output is the transpose of input on the last two dims.
    x_shape = x_param.tensor.shape
    out_shape = out_param.tensor.shape
    if not all(isinstance(s, ast.Name) for s in [*x_shape, *out_shape]):
        return None
    # x: (B, SX, SY)  →  out: (B, SY, SX)
    if (
        x_shape[0].id != out_shape[0].id
        or x_shape[1].id != out_shape[2].id
        or x_shape[2].id != out_shape[1].id
    ):
        return None

    pid_y, pid_x, pid_b = ir.block_axes

    return {
        "kernel_name": ir.name,
        "x_p": x_param.name,
        "out_p": out_param.name,
        "pid_y": pid_y,
        "pid_x": pid_x,
        "pid_b": pid_b,
        # Block sizes: pulled from closure if present (factory locals), else 128.
        "block_x_default": _closure_int(ir, "block_x", 128),
        "block_y_default": _closure_int(ir, "block_y", 128),
        "num_threads_default": _closure_int(ir, "num_threads", 256),
        # Runtime dimensions: TileLang uses ``T.dynamic(...)`` symbols — no source
        # default. Pick a typical workload; edit the emitted file to change.
        "num_batches_default": 4,
        "shape_x_default": 256,
        "shape_y_default": 512,
    }


def emit(info: dict) -> ast.Module:
    return ast.parse(_TEMPLATE.format(**info))
